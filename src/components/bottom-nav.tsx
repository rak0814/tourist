"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";

const navItems = [
  { href: "/", label: "홈", icon: HomeIcon },
  { href: "/board", label: "게시판", icon: BoardIcon },
  { href: "/chat", label: "채팅", icon: ChatIcon },
  { href: "/search", label: "검색", icon: SearchIcon },
  { href: "/profile", label: "마이", icon: UserIcon },
];

export function BottomNav() {
  const pathname = usePathname();

  return (
    <nav className="flex shrink-0 flex-col border-t border-zinc-200 bg-background dark:border-zinc-800">
      <div className="flex h-14 items-center justify-around">
      {navItems.map(({ href, label, icon: Icon }) => {
        const isActive = pathname === href || (href !== "/" && pathname.startsWith(href));
        return (
          <Link
            key={href}
            href={href}
            prefetch={true}
            className={`flex flex-col items-center gap-0.5 text-xs active:opacity-60 ${
              isActive
                ? "text-foreground"
                : "text-zinc-400 dark:text-zinc-500"
            }`}
          >
            <Icon className="h-5 w-5" />
            <span>{label}</span>
          </Link>
        );
      })}
      </div>
      <div className="h-[var(--safe-area-bottom)]" />
    </nav>
  );
}

